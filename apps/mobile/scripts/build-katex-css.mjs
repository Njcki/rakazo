// Inlines KaTeX's stylesheet and woff2 fonts for the offline math WebView (no network, no files).
// Run: node apps/mobile/scripts/build-katex-css.mjs (from repo root), after a katex version bump.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, "../package.json"));
const dist = dirname(require.resolve("katex/dist/katex.min.css"));
const css = readFileSync(join(dist, "katex.min.css"), "utf8");
const fonts = {};
const base = css.replace(/@font-face\{[^}]*\}/g, (rule) => {
  const file = /url\(fonts\/(KaTeX_[A-Za-z0-9-]+)\.woff2\)/.exec(rule)?.[1];
  if (!file) return "";
  const data = readFileSync(join(dist, "fonts", `${file}.woff2`)).toString("base64");
  fonts[file] = rule.replace(
    /src:[^}]*/,
    `src:url(data:font/woff2;base64,${data}) format("woff2")`,
  );
  return "";
});
const version = JSON.parse(readFileSync(join(dist, "../package.json"), "utf8")).version;
writeFileSync(
  join(here, "../lib/katex-css.generated.ts"),
  `// Generated by scripts/build-katex-css.mjs from katex ${version}. Do not edit.\n` +
    `export const KATEX_CSS = ${JSON.stringify(base)};\n` +
    `export const KATEX_FONTS: Record<string, string> = ${JSON.stringify(fonts, null, 1)};\n`,
);
console.log("css bytes", base.length, "fonts", Object.keys(fonts).length);
